% ---------------------------------------------------------------------
% Транзитивное замыкание по 'находиться_в'
% ---------------------------------------------------------------------
located_in(X, Y) :- edge(X, Y, 'находиться_в').
located_in(X, Y) :-
    edge(X, Z, 'находиться_в'),
    located_in(Z, Y).

% ---------------------------------------------------------------------
% Список технопарков в стране
% ---------------------------------------------------------------------
techpark_in_country(T, Country) :-
    node(T, _, technopark),
    located_in(T, Country).

techpark_in_russia(T) :-
    techpark_in_country(T, 'россия').

% ---------------------------------------------------------------------
% Регион, в котором находится технопарк
% ---------------------------------------------------------------------
region_of(T, R) :-
    node(R, _, region),
    located_in(T, R).

region_or_country(X, Y) :-
    edge(X, Z, 'находиться_в'),
    located_in(Z, Y).

% ---------------------------------------------------------------------
% Директор организации
% ---------------------------------------------------------------------
director_of(Org, P) :-
    edge(P, Org, 'директор'),
    node(P, _, person).

% ---------------------------------------------------------------------
% Технопарки без директора
% ---------------------------------------------------------------------
without_director(T) :-
    node(T, _, technopark),
    \+ director_of(T, _).

% ---------------------------------------------------------------------
% Кто контролирует технопарк
% ---------------------------------------------------------------------
controlled_by(T, Org) :-
    edge(Org, T, 'контролировать').

% ---------------------------------------------------------------------
% alias/2 — СХЕМА. Данные — edge(Short, Full, 'alias_of') в graph.pl.
% ---------------------------------------------------------------------
alias(Short, Full) :- edge(Short, Full, 'alias_of').
alias(Short, Full) :- attribute(Full, alias, Short).

% ---------------------------------------------------------------------
% human_readable/2 — СХЕМА. Данные — attribute(Id, label, L) в graph.pl.
% ---------------------------------------------------------------------
human_readable(Id, Label) :- attribute(Id, label, Label).

% ---------------------------------------------------------------------
% solution/1 + condition/1 — СХЕМА для ask_interactive().
% Данные — node(S, [], solution) + рёбра target/director в graph.pl.
% ---------------------------------------------------------------------
solution(S) :- node(S, _, solution).

condition(triplet('директор', P, Org)) :-
    edge(S, Org, 'target'),
    edge(S, P, 'director'),
    solution(S).